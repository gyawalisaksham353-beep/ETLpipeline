-- =====================================================
-- SILVER LAYER
-- Clean, typed, deduplicated and validated datasets.
-- =====================================================

CREATE SCHEMA IF NOT EXISTS {{ snowflake_database }}.SILVER;

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.SILVER.SILVER_SALES (
    TRANSACTION_ID VARCHAR(100),
    TRANSACTION_LINE_ID VARCHAR(100),
    STORE_ID VARCHAR(50),
    ITEM_ID VARCHAR(50),
    TRANSACTION_DATE DATE,

    QUANTITY NUMBER(10, 2),
    UNIT_PRICE NUMBER(12, 2),
    DISCOUNT_AMT NUMBER(12, 2),
    GROSS_SALES_AMT NUMBER(14, 2),
    NET_SALES_AMT NUMBER(14, 2),

    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ,
    BATCH_ID VARCHAR(500),

    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER (
    SNAPSHOT_DATE DATE,
    ITEM_ID VARCHAR(100),
    ITEM_NAME VARCHAR(500),
    BRAND VARCHAR(200),
    CATEGORY VARCHAR(200),
    SUBCLASS_ID VARCHAR(100),
    SUBCLASS_NAME VARCHAR(200),
    UNIT_COST NUMBER(12, 2),
    LIST_PRICE NUMBER(12, 2),

    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ,
    BATCH_ID VARCHAR(500),

    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.SILVER.SILVER_INVENTORY (
    SNAPSHOT_DATE DATE,
    ITEM_ID VARCHAR(100),
    STORE_ID VARCHAR(100),
    ON_HAND_QTY NUMBER(14, 2),
    UNIT_COST NUMBER(12, 2),
    INVENTORY_VALUE NUMBER(16, 2),

    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ,
    BATCH_ID VARCHAR(500),

    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.SILVER.SILVER_STORE_MASTER (
    SNAPSHOT_DATE DATE,
    STORE_ID VARCHAR(100),
    STORE_NAME VARCHAR(500),
    CITY VARCHAR(200),
    DISTRICT_ID VARCHAR(100),
    DISTRICT_NAME VARCHAR(200),
    REGION VARCHAR(200),
    STORE_TYPE VARCHAR(100),
    OPEN_DATE DATE,

    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ,
    BATCH_ID VARCHAR(500),

    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

-- Upgrade path for silver master tables created by earlier versions.
ALTER TABLE {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER
    ADD COLUMN IF NOT EXISTS SNAPSHOT_DATE DATE;

ALTER TABLE {{ snowflake_database }}.SILVER.SILVER_STORE_MASTER
    ADD COLUMN IF NOT EXISTS SNAPSHOT_DATE DATE;
