-- SCD2 location history linked to the district version effective that day.
MERGE INTO {{ snowflake_database }}.DIMENSIONS.DIM_LOCN AS TARGET
USING (
    WITH ORDERED AS (
        SELECT
            STORE_MASTER.STORE_ID,
            STORE_MASTER.SNAPSHOT_DATE,
            STORE_MASTER.STORE_NAME,
            STORE_MASTER.CITY,
            DIM_DISTRICT.DISTRICT_SK,
            STORE_MASTER.STORE_TYPE,
            STORE_MASTER.OPEN_DATE,
            MD5(CONCAT_WS(
                '|',
                COALESCE(STORE_MASTER.STORE_NAME, ''),
                COALESCE(STORE_MASTER.CITY, ''),
                COALESCE(DIM_DISTRICT.DISTRICT_SK, ''),
                COALESCE(STORE_MASTER.STORE_TYPE, ''),
                COALESCE(TO_CHAR(STORE_MASTER.OPEN_DATE, 'YYYY-MM-DD'), '')
            )) AS ATTR_HASH
        FROM {{ snowflake_database }}.SILVER.SILVER_STORE_MASTER AS STORE_MASTER
        LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DISTRICT AS DIM_DISTRICT
            ON DIM_DISTRICT.DISTRICT_ID = STORE_MASTER.DISTRICT_ID
            AND STORE_MASTER.SNAPSHOT_DATE BETWEEN
                DIM_DISTRICT.EFFECTIVE_FROM
                AND COALESCE(DIM_DISTRICT.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    ),
    FLAGGED AS (
        SELECT
            ORDERED.*,
            LAG(ATTR_HASH) OVER (
                PARTITION BY STORE_ID
                ORDER BY SNAPSHOT_DATE
            ) AS PREV_ATTR_HASH
        FROM ORDERED
    ),
    CHANGE_FLAGS AS (
        SELECT
            FLAGGED.*,
            IFF(PREV_ATTR_HASH IS NULL OR PREV_ATTR_HASH <> ATTR_HASH, 1, 0)
                AS IS_CHANGE
        FROM FLAGGED
    ),
    GROUPED AS (
        SELECT
            CHANGE_FLAGS.*,
            SUM(IS_CHANGE) OVER (
                PARTITION BY STORE_ID
                ORDER BY SNAPSHOT_DATE
            ) AS VERSION_GROUP
        FROM CHANGE_FLAGS
    ),
    VERSIONS AS (
        SELECT
            STORE_ID,
            VERSION_GROUP,
            MIN(SNAPSHOT_DATE) AS EFFECTIVE_FROM,
            ANY_VALUE(STORE_NAME) AS STORE_NAME,
            ANY_VALUE(CITY) AS CITY,
            ANY_VALUE(DISTRICT_SK) AS DISTRICT_SK,
            ANY_VALUE(STORE_TYPE) AS STORE_TYPE,
            ANY_VALUE(OPEN_DATE) AS OPEN_DATE
        FROM GROUPED
        GROUP BY STORE_ID, VERSION_GROUP
    ),
    VERSIONED AS (
        SELECT
            VERSIONS.*,
            DATEADD(
                DAY,
                -1,
                LEAD(EFFECTIVE_FROM) OVER (
                    PARTITION BY STORE_ID
                    ORDER BY VERSION_GROUP
                )
            ) AS EFFECTIVE_TO,
            ROW_NUMBER() OVER (
                PARTITION BY STORE_ID
                ORDER BY VERSION_GROUP
            ) AS VERSION_NUM
        FROM VERSIONS
    )
    SELECT
        MD5(CONCAT_WS(
            '|',
            STORE_ID,
            TO_CHAR(EFFECTIVE_FROM, 'YYYY-MM-DD')
        )) AS LOCN_SK,
        STORE_ID,
        STORE_NAME,
        CITY,
        DISTRICT_SK,
        STORE_TYPE,
        OPEN_DATE,
        EFFECTIVE_FROM,
        EFFECTIVE_TO,
        EFFECTIVE_TO IS NULL AS IS_CURRENT,
        VERSION_NUM
    FROM VERSIONED
) AS SOURCE
ON TARGET.LOCN_SK = SOURCE.LOCN_SK

WHEN MATCHED AND (
    TARGET.LOCN_ID IS DISTINCT FROM SOURCE.STORE_ID
    OR TARGET.STORE_NAME IS DISTINCT FROM SOURCE.STORE_NAME
    OR TARGET.CITY IS DISTINCT FROM SOURCE.CITY
    OR TARGET.DISTRICT_SK IS DISTINCT FROM SOURCE.DISTRICT_SK
    OR TARGET.STORE_TYPE IS DISTINCT FROM SOURCE.STORE_TYPE
    OR TARGET.OPEN_DATE IS DISTINCT FROM SOURCE.OPEN_DATE
    OR TARGET.EFFECTIVE_FROM IS DISTINCT FROM SOURCE.EFFECTIVE_FROM
    OR TARGET.EFFECTIVE_TO IS DISTINCT FROM SOURCE.EFFECTIVE_TO
    OR TARGET.IS_CURRENT IS DISTINCT FROM SOURCE.IS_CURRENT
    OR TARGET.VERSION_NUM IS DISTINCT FROM SOURCE.VERSION_NUM
) THEN UPDATE SET
    TARGET.LOCN_ID = SOURCE.STORE_ID,
    TARGET.STORE_NAME = SOURCE.STORE_NAME,
    TARGET.CITY = SOURCE.CITY,
    TARGET.DISTRICT_SK = SOURCE.DISTRICT_SK,
    TARGET.STORE_TYPE = SOURCE.STORE_TYPE,
    TARGET.OPEN_DATE = SOURCE.OPEN_DATE,
    TARGET.EFFECTIVE_FROM = SOURCE.EFFECTIVE_FROM,
    TARGET.EFFECTIVE_TO = SOURCE.EFFECTIVE_TO,
    TARGET.IS_CURRENT = SOURCE.IS_CURRENT,
    TARGET.VERSION_NUM = SOURCE.VERSION_NUM,
    TARGET.UPDATED_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    LOCN_SK,
    STORE_ID,
    LOCN_ID,
    STORE_NAME,
    CITY,
    DISTRICT_SK,
    STORE_TYPE,
    OPEN_DATE,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    VERSION_NUM,
    CREATED_TS
)
VALUES (
    SOURCE.LOCN_SK,
    SOURCE.STORE_ID,
    SOURCE.STORE_ID,
    SOURCE.STORE_NAME,
    SOURCE.CITY,
    SOURCE.DISTRICT_SK,
    SOURCE.STORE_TYPE,
    SOURCE.OPEN_DATE,
    SOURCE.EFFECTIVE_FROM,
    SOURCE.EFFECTIVE_TO,
    SOURCE.IS_CURRENT,
    SOURCE.VERSION_NUM,
    CURRENT_TIMESTAMP()
);
