-- SCD2 item attributes; BRAND is overwritten in place (SCD1).
MERGE INTO {{ snowflake_database }}.DIMENSIONS.DIM_ITEM AS TARGET
USING (
    WITH ORDERED AS (
        SELECT
            ITEM_MASTER.ITEM_ID,
            ITEM_MASTER.SNAPSHOT_DATE,
            ITEM_MASTER.ITEM_NAME,
            DIM_SUBCLASS.SUBCLASS_SK,
            ITEM_MASTER.UNIT_COST,
            ITEM_MASTER.LIST_PRICE,
            MD5(CONCAT_WS(
                '|',
                COALESCE(ITEM_MASTER.ITEM_NAME, ''),
                COALESCE(DIM_SUBCLASS.SUBCLASS_SK, ''),
                COALESCE(TO_CHAR(ITEM_MASTER.UNIT_COST), ''),
                COALESCE(TO_CHAR(ITEM_MASTER.LIST_PRICE), '')
            )) AS ATTR_HASH
        FROM {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER AS ITEM_MASTER
        LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_SUBCLASS AS DIM_SUBCLASS
            ON DIM_SUBCLASS.SUBCLASS_ID = ITEM_MASTER.SUBCLASS_ID
            AND ITEM_MASTER.SNAPSHOT_DATE BETWEEN
                DIM_SUBCLASS.EFFECTIVE_FROM
                AND COALESCE(DIM_SUBCLASS.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    ),
    FLAGGED AS (
        SELECT
            ORDERED.*,
            LAG(ATTR_HASH) OVER (
                PARTITION BY ITEM_ID
                ORDER BY SNAPSHOT_DATE
            ) AS PREV_ATTR_HASH
        FROM ORDERED
    ),
    CHANGE_FLAGS AS (
        SELECT
            FLAGGED.*,
            IFF(PREV_ATTR_HASH IS NULL OR PREV_ATTR_HASH <> ATTR_HASH, 1, 0)
                AS IS_CHANGE
        FROM FLAGGED
    ),
    GROUPED AS (
        SELECT
            CHANGE_FLAGS.*,
            SUM(IS_CHANGE) OVER (
                PARTITION BY ITEM_ID
                ORDER BY SNAPSHOT_DATE
            ) AS VERSION_GROUP
        FROM CHANGE_FLAGS
    ),
    VERSIONS AS (
        SELECT
            ITEM_ID,
            VERSION_GROUP,
            MIN(SNAPSHOT_DATE) AS EFFECTIVE_FROM,
            ANY_VALUE(ITEM_NAME) AS ITEM_NAME,
            ANY_VALUE(SUBCLASS_SK) AS SUBCLASS_SK,
            ANY_VALUE(UNIT_COST) AS UNIT_COST,
            ANY_VALUE(LIST_PRICE) AS LIST_PRICE
        FROM GROUPED
        GROUP BY ITEM_ID, VERSION_GROUP
    ),
    VERSIONED AS (
        SELECT
            VERSIONS.*,
            DATEADD(
                DAY,
                -1,
                LEAD(EFFECTIVE_FROM) OVER (
                    PARTITION BY ITEM_ID
                    ORDER BY VERSION_GROUP
                )
            ) AS EFFECTIVE_TO,
            ROW_NUMBER() OVER (
                PARTITION BY ITEM_ID
                ORDER BY VERSION_GROUP
            ) AS VERSION_NUM
        FROM VERSIONS
    ),
    LATEST_BRAND AS (
        SELECT ITEM_ID, BRAND
        FROM {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY ITEM_ID
            ORDER BY SNAPSHOT_DATE DESC, SRC_ROW_NUM DESC
        ) = 1
    )
    SELECT
        MD5(CONCAT_WS(
            '|',
            VERSIONED.ITEM_ID,
            TO_CHAR(VERSIONED.EFFECTIVE_FROM, 'YYYY-MM-DD')
        )) AS ITEM_SK,
        VERSIONED.ITEM_ID,
        VERSIONED.ITEM_NAME,
        LATEST_BRAND.BRAND,
        VERSIONED.SUBCLASS_SK,
        VERSIONED.UNIT_COST,
        VERSIONED.LIST_PRICE,
        VERSIONED.EFFECTIVE_FROM,
        VERSIONED.EFFECTIVE_TO,
        VERSIONED.EFFECTIVE_TO IS NULL AS IS_CURRENT,
        VERSIONED.VERSION_NUM
    FROM VERSIONED
    INNER JOIN LATEST_BRAND
        ON LATEST_BRAND.ITEM_ID = VERSIONED.ITEM_ID
) AS SOURCE
ON TARGET.ITEM_SK = SOURCE.ITEM_SK

WHEN MATCHED AND (
    TARGET.ITEM_NAME IS DISTINCT FROM SOURCE.ITEM_NAME
    OR TARGET.BRAND IS DISTINCT FROM SOURCE.BRAND
    OR TARGET.SUBCLASS_SK IS DISTINCT FROM SOURCE.SUBCLASS_SK
    OR TARGET.UNIT_COST IS DISTINCT FROM SOURCE.UNIT_COST
    OR TARGET.LIST_PRICE IS DISTINCT FROM SOURCE.LIST_PRICE
    OR TARGET.EFFECTIVE_FROM IS DISTINCT FROM SOURCE.EFFECTIVE_FROM
    OR TARGET.EFFECTIVE_TO IS DISTINCT FROM SOURCE.EFFECTIVE_TO
    OR TARGET.IS_CURRENT IS DISTINCT FROM SOURCE.IS_CURRENT
    OR TARGET.VERSION_NUM IS DISTINCT FROM SOURCE.VERSION_NUM
) THEN UPDATE SET
    TARGET.ITEM_NAME = SOURCE.ITEM_NAME,
    TARGET.BRAND = SOURCE.BRAND,
    TARGET.SUBCLASS_SK = SOURCE.SUBCLASS_SK,
    TARGET.UNIT_COST = SOURCE.UNIT_COST,
    TARGET.LIST_PRICE = SOURCE.LIST_PRICE,
    TARGET.EFFECTIVE_FROM = SOURCE.EFFECTIVE_FROM,
    TARGET.EFFECTIVE_TO = SOURCE.EFFECTIVE_TO,
    TARGET.IS_CURRENT = SOURCE.IS_CURRENT,
    TARGET.VERSION_NUM = SOURCE.VERSION_NUM,
    TARGET.UPDATED_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    ITEM_SK,
    ITEM_ID,
    ITEM_NAME,
    BRAND,
    SUBCLASS_SK,
    UNIT_COST,
    LIST_PRICE,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    VERSION_NUM,
    CREATED_TS
)
VALUES (
    SOURCE.ITEM_SK,
    SOURCE.ITEM_ID,
    SOURCE.ITEM_NAME,
    SOURCE.BRAND,
    SOURCE.SUBCLASS_SK,
    SOURCE.UNIT_COST,
    SOURCE.LIST_PRICE,
    SOURCE.EFFECTIVE_FROM,
    SOURCE.EFFECTIVE_TO,
    SOURCE.IS_CURRENT,
    SOURCE.VERSION_NUM,
    CURRENT_TIMESTAMP()
);
