MERGE INTO {{ snowflake_database }}.DIMENSIONS.DIM_REGION AS TARGET
USING (
    SELECT
        MD5(UPPER(TRIM(REGION))) AS REGION_SK,
        MIN(TRIM(REGION)) AS REGION_NAME
    FROM {{ snowflake_database }}.SILVER.SILVER_STORE_MASTER
    WHERE COALESCE(TRIM(REGION), '') <> ''
    GROUP BY UPPER(TRIM(REGION))
) AS SOURCE
ON TARGET.REGION_SK = SOURCE.REGION_SK
WHEN MATCHED AND TARGET.REGION_NAME IS DISTINCT FROM SOURCE.REGION_NAME
    THEN UPDATE SET REGION_NAME = SOURCE.REGION_NAME
WHEN NOT MATCHED THEN INSERT (REGION_SK, REGION_NAME)
    VALUES (SOURCE.REGION_SK, SOURCE.REGION_NAME);
