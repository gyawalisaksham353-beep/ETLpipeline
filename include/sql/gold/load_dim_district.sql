MERGE INTO {{ snowflake_database }}.DIMENSIONS.DIM_DISTRICT AS TARGET
USING (
WITH SNAPSHOTS AS (
    SELECT
        STORE_MASTER.DISTRICT_ID,
        STORE_MASTER.SNAPSHOT_DATE,
        ANY_VALUE(STORE_MASTER.DISTRICT_NAME) AS DISTRICT_NAME,
        ANY_VALUE(STORE_MASTER.REGION) AS REGION_NAME
    FROM {{ snowflake_database }}.SILVER.SILVER_STORE_MASTER AS STORE_MASTER
    WHERE COALESCE(TRIM(STORE_MASTER.DISTRICT_ID), '') <> ''
    GROUP BY
        STORE_MASTER.DISTRICT_ID,
        STORE_MASTER.SNAPSHOT_DATE
),
ORDERED AS (
    SELECT
        SNAPSHOTS.DISTRICT_ID,
        SNAPSHOTS.SNAPSHOT_DATE,
        SNAPSHOTS.DISTRICT_NAME,
        DIM_REGION.REGION_SK,
        MD5(CONCAT_WS(
            '|',
            COALESCE(SNAPSHOTS.DISTRICT_NAME, ''),
            COALESCE(DIM_REGION.REGION_SK, '')
        )) AS ATTR_HASH
    FROM SNAPSHOTS
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_REGION AS DIM_REGION
        ON DIM_REGION.REGION_SK =
            MD5(UPPER(TRIM(SNAPSHOTS.REGION_NAME)))
),
FLAGGED AS (
    SELECT
        ORDERED.*,
        LAG(ATTR_HASH) OVER (
            PARTITION BY DISTRICT_ID
            ORDER BY SNAPSHOT_DATE
        ) AS PREV_ATTR_HASH
    FROM ORDERED
),
CHANGE_FLAGS AS (
    SELECT
        FLAGGED.*,
        IFF(PREV_ATTR_HASH IS NULL OR PREV_ATTR_HASH <> ATTR_HASH, 1, 0) AS IS_CHANGE
    FROM FLAGGED
),
GROUPED AS (
    SELECT
        CHANGE_FLAGS.*,
        SUM(IS_CHANGE) OVER (
            PARTITION BY DISTRICT_ID
            ORDER BY SNAPSHOT_DATE
        ) AS VERSION_GROUP
    FROM CHANGE_FLAGS
),
VERSIONS AS (
    SELECT
        DISTRICT_ID,
        VERSION_GROUP,
        MIN(SNAPSHOT_DATE) AS EFFECTIVE_FROM,
        ANY_VALUE(DISTRICT_NAME) AS DISTRICT_NAME,
        ANY_VALUE(REGION_SK) AS REGION_SK
    FROM GROUPED
    GROUP BY DISTRICT_ID, VERSION_GROUP
),
VERSIONED AS (
    SELECT
        VERSIONS.*,
        DATEADD(
            DAY,
            -1,
            LEAD(EFFECTIVE_FROM) OVER (
                PARTITION BY DISTRICT_ID
                ORDER BY VERSION_GROUP
            )
        ) AS EFFECTIVE_TO,
        ROW_NUMBER() OVER (
            PARTITION BY DISTRICT_ID
            ORDER BY VERSION_GROUP
        ) AS VERSION_NUM
    FROM VERSIONS
)
SELECT
    MD5(CONCAT_WS(
        '|',
        DISTRICT_ID,
        TO_CHAR(EFFECTIVE_FROM, 'YYYY-MM-DD')
    )) AS DISTRICT_SK,
    DISTRICT_ID,
    DISTRICT_NAME,
    REGION_SK,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    EFFECTIVE_TO IS NULL AS IS_CURRENT,
    VERSION_NUM
FROM VERSIONED
) AS SOURCE
ON TARGET.DISTRICT_SK = SOURCE.DISTRICT_SK
WHEN MATCHED AND (
    TARGET.DISTRICT_NAME IS DISTINCT FROM SOURCE.DISTRICT_NAME
    OR TARGET.REGION_SK IS DISTINCT FROM SOURCE.REGION_SK
    OR TARGET.EFFECTIVE_FROM IS DISTINCT FROM SOURCE.EFFECTIVE_FROM
    OR TARGET.EFFECTIVE_TO IS DISTINCT FROM SOURCE.EFFECTIVE_TO
    OR TARGET.IS_CURRENT IS DISTINCT FROM SOURCE.IS_CURRENT
    OR TARGET.VERSION_NUM IS DISTINCT FROM SOURCE.VERSION_NUM
) THEN UPDATE SET
    TARGET.DISTRICT_NAME = SOURCE.DISTRICT_NAME,
    TARGET.REGION_SK = SOURCE.REGION_SK,
    TARGET.EFFECTIVE_FROM = SOURCE.EFFECTIVE_FROM,
    TARGET.EFFECTIVE_TO = SOURCE.EFFECTIVE_TO,
    TARGET.IS_CURRENT = SOURCE.IS_CURRENT,
    TARGET.VERSION_NUM = SOURCE.VERSION_NUM,
    TARGET.UPDATED_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    DISTRICT_SK,
    DISTRICT_ID,
    DISTRICT_NAME,
    REGION_SK,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    VERSION_NUM,
    CREATED_TS
)
VALUES (
    SOURCE.DISTRICT_SK,
    SOURCE.DISTRICT_ID,
    SOURCE.DISTRICT_NAME,
    SOURCE.REGION_SK,
    SOURCE.EFFECTIVE_FROM,
    SOURCE.EFFECTIVE_TO,
    SOURCE.IS_CURRENT,
    SOURCE.VERSION_NUM,
    CURRENT_TIMESTAMP()
);
