-- =====================================================
-- GOLD LAYER
-- Dimensional model for business reporting.
-- Item and store hierarchies are normalized as snowflake dimensions.
-- =====================================================

CREATE SCHEMA IF NOT EXISTS {{ snowflake_database }}.DIMENSIONS;
CREATE SCHEMA IF NOT EXISTS {{ snowflake_database }}.FACTS;

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.DIMENSIONS.DIM_CATEGORY (
    CATEGORY_SK VARCHAR(32) NOT NULL,
    CATEGORY_NAME VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.DIMENSIONS.DIM_SUBCLASS (
    SUBCLASS_SK VARCHAR(32) NOT NULL,
    SUBCLASS_ID VARCHAR(100) NOT NULL,
    SUBCLASS_NAME VARCHAR(200),
    CATEGORY_SK VARCHAR(32),
    EFFECTIVE_FROM DATE,
    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN,
    VERSION_NUM NUMBER,
    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.DIMENSIONS.DIM_REGION (
    REGION_SK VARCHAR(32) NOT NULL,
    REGION_NAME VARCHAR(200) NOT NULL
