    MONTH_NAME VARCHAR(20),
    QUARTER_NUM NUMBER,
    YEAR_NUM NUMBER,
    FISCAL_YEAR_NUM NUMBER,
    FISCAL_QUARTER_NUM NUMBER,
    WEEK_OF_YEAR NUMBER,
    IS_WEEKEND BOOLEAN
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.FACTS.FCT_SALES (
    FCT_SALES_SK VARCHAR(32) NOT NULL,
    TRANSACTION_ID VARCHAR(100),
    TRANSACTION_LINE_ID VARCHAR(100),
    STORE_ID VARCHAR(50),
    ITEM_ID VARCHAR(50),
    DATE_SK NUMBER,
    ITEM_SK VARCHAR(32),
    LOCN_SK VARCHAR(32),
    QUANTITY NUMBER(10, 2),
    UNIT_PRICE NUMBER(12, 2),
    DISCOUNT_AMT NUMBER(12, 2),
    GROSS_SALES_AMT NUMBER(14, 2),
    NET_SALES_AMT NUMBER(14, 2),
    SRC_FILE_NM VARCHAR(500),
    BATCH_ID VARCHAR(500),
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.FACTS.FCT_INVENTORY (
    FCT_INVENTORY_SK VARCHAR(32) NOT NULL,
    SNAPSHOT_DATE DATE,
    DATE_SK NUMBER,
    ITEM_ID VARCHAR(100),
    STORE_ID VARCHAR(100),
    ITEM_SK VARCHAR(32),
    LOCN_SK VARCHAR(32),
    ON_HAND_QTY NUMBER(14, 2),
    UNIT_COST NUMBER(12, 2),
    INVENTORY_VALUE NUMBER(16, 2),
    EFFECTIVE_FROM DATE,
    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN,
    SRC_FILE_NM VARCHAR(500),
    BATCH_ID VARCHAR(500),
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

