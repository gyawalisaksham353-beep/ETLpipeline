    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN,
    VERSION_NUM NUMBER,
    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.DIMENSIONS.DIM_ITEM (
    ITEM_SK VARCHAR(32) NOT NULL,
    ITEM_ID VARCHAR(100) NOT NULL,
    ITEM_NAME VARCHAR(500),
    BRAND VARCHAR(200),
    SUBCLASS_SK VARCHAR(32),
    UNIT_COST NUMBER(12, 2),
