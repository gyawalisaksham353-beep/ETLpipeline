    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN,
    VERSION_NUM NUMBER,
    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.DIMENSIONS.DIM_LOCN (
    LOCN_SK VARCHAR(32) NOT NULL,
    STORE_ID VARCHAR(100) NOT NULL,
    STORE_NAME VARCHAR(500),
    CITY VARCHAR(200),
    DISTRICT_SK VARCHAR(32),
    STORE_TYPE VARCHAR(100),
    OPEN_DATE DATE,
    EFFECTIVE_FROM DATE,
    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN,
    VERSION_NUM NUMBER,
    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.DIMENSIONS.DIM_DAY (
    DATE_SK NUMBER NOT NULL,
    FULL_DATE DATE NOT NULL,
    DAY_NAME VARCHAR(20),
    DAY_OF_WEEK NUMBER,
    DAY_OF_MONTH NUMBER,
    DAY_OF_YEAR NUMBER,
