-- Grain: item × location × snapshot date. Older positions are closed, not deleted.
MERGE INTO {{ snowflake_database }}.FACTS.FCT_INVENTORY AS TARGET
USING (
    WITH OBSERVATIONS AS (
        SELECT
            SILVER_INVENTORY.SNAPSHOT_DATE,
            SILVER_INVENTORY.ITEM_ID,
            SILVER_INVENTORY.STORE_ID,
            DIM_DAY.DATE_SK,
            DIM_ITEM.ITEM_SK,
            DIM_LOCN.LOCN_SK,
            SILVER_INVENTORY.ON_HAND_QTY,
            SILVER_INVENTORY.UNIT_COST,
            SILVER_INVENTORY.INVENTORY_VALUE,
            SILVER_INVENTORY.SRC_FILE_NM,
            SILVER_INVENTORY.BATCH_ID
        FROM {{ snowflake_database }}.SILVER.SILVER_INVENTORY AS SILVER_INVENTORY
        INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_ITEM AS DIM_ITEM
            ON DIM_ITEM.ITEM_ID = SILVER_INVENTORY.ITEM_ID
            AND SILVER_INVENTORY.SNAPSHOT_DATE BETWEEN
                DIM_ITEM.EFFECTIVE_FROM
                AND COALESCE(DIM_ITEM.EFFECTIVE_TO, TO_DATE('9999-12-31'))
        INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_LOCN AS DIM_LOCN
            ON DIM_LOCN.STORE_ID = SILVER_INVENTORY.STORE_ID
            AND SILVER_INVENTORY.SNAPSHOT_DATE BETWEEN
                DIM_LOCN.EFFECTIVE_FROM
                AND COALESCE(DIM_LOCN.EFFECTIVE_TO, TO_DATE('9999-12-31'))
        INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DAY AS DIM_DAY
            ON DIM_DAY.FULL_DATE = SILVER_INVENTORY.SNAPSHOT_DATE
    ),
    POSITIONED AS (
        SELECT
            OBSERVATIONS.*,
            LEAD(SNAPSHOT_DATE) OVER (
                PARTITION BY ITEM_ID, STORE_ID
                ORDER BY SNAPSHOT_DATE
            ) AS NEXT_SNAPSHOT_DATE
        FROM OBSERVATIONS
    )
    SELECT
        MD5(CONCAT_WS(
            '|',
            ITEM_ID,
            STORE_ID,
            TO_CHAR(SNAPSHOT_DATE, 'YYYY-MM-DD')
        )) AS FCT_INVENTORY_SK,
        SNAPSHOT_DATE,
        DATE_SK,
        ITEM_ID,
        STORE_ID,
        ITEM_SK,
        LOCN_SK,
        ON_HAND_QTY,
        UNIT_COST,
        INVENTORY_VALUE,
        SNAPSHOT_DATE AS EFFECTIVE_FROM,
        DATEADD(DAY, -1, NEXT_SNAPSHOT_DATE) AS EFFECTIVE_TO,
        NEXT_SNAPSHOT_DATE IS NULL AS IS_CURRENT,
        SRC_FILE_NM,
        BATCH_ID
    FROM POSITIONED
) AS SOURCE
ON TARGET.ITEM_ID = SOURCE.ITEM_ID
    AND TARGET.STORE_ID = SOURCE.STORE_ID
    AND TARGET.SNAPSHOT_DATE = SOURCE.SNAPSHOT_DATE

WHEN MATCHED AND (
    TARGET.DATE_SK IS DISTINCT FROM SOURCE.DATE_SK
    OR TARGET.ITEM_SK IS DISTINCT FROM SOURCE.ITEM_SK
    OR TARGET.LOCN_SK IS DISTINCT FROM SOURCE.LOCN_SK
    OR TARGET.ON_HAND_QTY IS DISTINCT FROM SOURCE.ON_HAND_QTY
    OR TARGET.UNIT_COST IS DISTINCT FROM SOURCE.UNIT_COST
    OR TARGET.INVENTORY_VALUE IS DISTINCT FROM SOURCE.INVENTORY_VALUE
    OR TARGET.EFFECTIVE_FROM IS DISTINCT FROM SOURCE.EFFECTIVE_FROM
    OR TARGET.EFFECTIVE_TO IS DISTINCT FROM SOURCE.EFFECTIVE_TO
    OR TARGET.IS_CURRENT IS DISTINCT FROM SOURCE.IS_CURRENT
    OR TARGET.SRC_FILE_NM IS DISTINCT FROM SOURCE.SRC_FILE_NM
    OR TARGET.BATCH_ID IS DISTINCT FROM SOURCE.BATCH_ID
) THEN UPDATE SET
    TARGET.DATE_SK = SOURCE.DATE_SK,
    TARGET.ITEM_SK = SOURCE.ITEM_SK,
    TARGET.LOCN_SK = SOURCE.LOCN_SK,
    TARGET.ON_HAND_QTY = SOURCE.ON_HAND_QTY,
    TARGET.UNIT_COST = SOURCE.UNIT_COST,
    TARGET.INVENTORY_VALUE = SOURCE.INVENTORY_VALUE,
    TARGET.EFFECTIVE_FROM = SOURCE.EFFECTIVE_FROM,
    TARGET.EFFECTIVE_TO = SOURCE.EFFECTIVE_TO,
    TARGET.IS_CURRENT = SOURCE.IS_CURRENT,
    TARGET.SRC_FILE_NM = SOURCE.SRC_FILE_NM,
    TARGET.BATCH_ID = SOURCE.BATCH_ID,
    TARGET.LOAD_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    FCT_INVENTORY_SK,
    SNAPSHOT_DATE,
    DATE_SK,
    ITEM_ID,
    STORE_ID,
    ITEM_SK,
    LOCN_SK,
    ON_HAND_QTY,
    UNIT_COST,
    INVENTORY_VALUE,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    SRC_FILE_NM,
    BATCH_ID
)
VALUES (
    SOURCE.FCT_INVENTORY_SK,
    SOURCE.SNAPSHOT_DATE,
    SOURCE.DATE_SK,
    SOURCE.ITEM_ID,
    SOURCE.STORE_ID,
    SOURCE.ITEM_SK,
    SOURCE.LOCN_SK,
    SOURCE.ON_HAND_QTY,
    SOURCE.UNIT_COST,
    SOURCE.INVENTORY_VALUE,
    SOURCE.EFFECTIVE_FROM,
    SOURCE.EFFECTIVE_TO,
    SOURCE.IS_CURRENT,
    SOURCE.SRC_FILE_NM,
    SOURCE.BATCH_ID
);
