MERGE INTO {{ snowflake_database }}.DIMENSIONS.DIM_CATEGORY AS TARGET
USING (
    SELECT
        MD5(UPPER(TRIM(CATEGORY))) AS CATEGORY_SK,
        MIN(TRIM(CATEGORY)) AS CATEGORY_NAME
    FROM {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER
    WHERE COALESCE(TRIM(CATEGORY), '') <> ''
    GROUP BY UPPER(TRIM(CATEGORY))
) AS SOURCE
ON TARGET.CATEGORY_SK = SOURCE.CATEGORY_SK
WHEN MATCHED AND TARGET.CATEGORY_NAME IS DISTINCT FROM SOURCE.CATEGORY_NAME
    THEN UPDATE SET CATEGORY_NAME = SOURCE.CATEGORY_NAME
WHEN NOT MATCHED THEN INSERT (CATEGORY_SK, CATEGORY_NAME)
    VALUES (SOURCE.CATEGORY_SK, SOURCE.CATEGORY_NAME);
