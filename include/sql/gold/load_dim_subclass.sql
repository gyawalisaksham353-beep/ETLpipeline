MERGE INTO {{ snowflake_database }}.DIMENSIONS.DIM_SUBCLASS AS TARGET
USING (
WITH SNAPSHOTS AS (
    SELECT
        ITEM_MASTER.SUBCLASS_ID,
        ITEM_MASTER.SNAPSHOT_DATE,
        ANY_VALUE(ITEM_MASTER.SUBCLASS_NAME) AS SUBCLASS_NAME,
        ANY_VALUE(ITEM_MASTER.CATEGORY) AS CATEGORY_NAME
    FROM {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER AS ITEM_MASTER
    WHERE COALESCE(TRIM(ITEM_MASTER.SUBCLASS_ID), '') <> ''
    GROUP BY
        ITEM_MASTER.SUBCLASS_ID,
        ITEM_MASTER.SNAPSHOT_DATE
),
ORDERED AS (
    SELECT
        SNAPSHOTS.SUBCLASS_ID,
        SNAPSHOTS.SNAPSHOT_DATE,
        SNAPSHOTS.SUBCLASS_NAME,
        DIM_CATEGORY.CATEGORY_SK,
        MD5(CONCAT_WS(
            '|',
            COALESCE(SNAPSHOTS.SUBCLASS_NAME, ''),
            COALESCE(DIM_CATEGORY.CATEGORY_SK, '')
        )) AS ATTR_HASH
    FROM SNAPSHOTS
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_CATEGORY AS DIM_CATEGORY
        ON DIM_CATEGORY.CATEGORY_SK =
            MD5(UPPER(TRIM(SNAPSHOTS.CATEGORY_NAME)))
),
FLAGGED AS (
    SELECT
        ORDERED.*,
        LAG(ATTR_HASH) OVER (
            PARTITION BY SUBCLASS_ID
            ORDER BY SNAPSHOT_DATE
        ) AS PREV_ATTR_HASH
    FROM ORDERED
),
CHANGE_FLAGS AS (
    SELECT
        FLAGGED.*,
        IFF(PREV_ATTR_HASH IS NULL OR PREV_ATTR_HASH <> ATTR_HASH, 1, 0) AS IS_CHANGE
    FROM FLAGGED
),
GROUPED AS (
    SELECT
        CHANGE_FLAGS.*,
        SUM(IS_CHANGE) OVER (
            PARTITION BY SUBCLASS_ID
            ORDER BY SNAPSHOT_DATE
        ) AS VERSION_GROUP
    FROM CHANGE_FLAGS
),
VERSIONS AS (
    SELECT
        SUBCLASS_ID,
        VERSION_GROUP,
        MIN(SNAPSHOT_DATE) AS EFFECTIVE_FROM,
        ANY_VALUE(SUBCLASS_NAME) AS SUBCLASS_NAME,
        ANY_VALUE(CATEGORY_SK) AS CATEGORY_SK
    FROM GROUPED
    GROUP BY SUBCLASS_ID, VERSION_GROUP
),
VERSIONED AS (
    SELECT
        VERSIONS.*,
        DATEADD(
            DAY,
            -1,
            LEAD(EFFECTIVE_FROM) OVER (
                PARTITION BY SUBCLASS_ID
                ORDER BY VERSION_GROUP
            )
        ) AS EFFECTIVE_TO,
        ROW_NUMBER() OVER (
            PARTITION BY SUBCLASS_ID
            ORDER BY VERSION_GROUP
        ) AS VERSION_NUM
    FROM VERSIONS
)
SELECT
    MD5(CONCAT_WS(
        '|',
        SUBCLASS_ID,
        TO_CHAR(EFFECTIVE_FROM, 'YYYY-MM-DD')
    )) AS SUBCLASS_SK,
    SUBCLASS_ID,
    SUBCLASS_NAME,
    CATEGORY_SK,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    EFFECTIVE_TO IS NULL AS IS_CURRENT,
    VERSION_NUM
FROM VERSIONED
) AS SOURCE
ON TARGET.SUBCLASS_SK = SOURCE.SUBCLASS_SK
WHEN MATCHED AND (
    TARGET.SUBCLASS_NAME IS DISTINCT FROM SOURCE.SUBCLASS_NAME
    OR TARGET.CATEGORY_SK IS DISTINCT FROM SOURCE.CATEGORY_SK
    OR TARGET.EFFECTIVE_FROM IS DISTINCT FROM SOURCE.EFFECTIVE_FROM
    OR TARGET.EFFECTIVE_TO IS DISTINCT FROM SOURCE.EFFECTIVE_TO
    OR TARGET.IS_CURRENT IS DISTINCT FROM SOURCE.IS_CURRENT
    OR TARGET.VERSION_NUM IS DISTINCT FROM SOURCE.VERSION_NUM
) THEN UPDATE SET
    TARGET.SUBCLASS_NAME = SOURCE.SUBCLASS_NAME,
    TARGET.CATEGORY_SK = SOURCE.CATEGORY_SK,
    TARGET.EFFECTIVE_FROM = SOURCE.EFFECTIVE_FROM,
    TARGET.EFFECTIVE_TO = SOURCE.EFFECTIVE_TO,
    TARGET.IS_CURRENT = SOURCE.IS_CURRENT,
    TARGET.VERSION_NUM = SOURCE.VERSION_NUM,
    TARGET.UPDATED_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    SUBCLASS_SK,
    SUBCLASS_ID,
    SUBCLASS_NAME,
    CATEGORY_SK,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    VERSION_NUM,
    CREATED_TS
)
VALUES (
    SOURCE.SUBCLASS_SK,
    SOURCE.SUBCLASS_ID,
    SOURCE.SUBCLASS_NAME,
    SOURCE.CATEGORY_SK,
    SOURCE.EFFECTIVE_FROM,
    SOURCE.EFFECTIVE_TO,
    SOURCE.IS_CURRENT,
    SOURCE.VERSION_NUM,
    CURRENT_TIMESTAMP()
);
