-- Calendar dimension covering the sales and inventory date ranges.
MERGE INTO {{ snowflake_database }}.DIMENSIONS.DIM_DAY AS TARGET
USING (
    WITH BOUNDS AS (
        SELECT
            LEAST(
                COALESCE(
                    (SELECT MIN(TRANSACTION_DATE) FROM {{ snowflake_database }}.SILVER.SILVER_SALES),
                    CURRENT_DATE()
                ),
                COALESCE(
                    (SELECT MIN(SNAPSHOT_DATE) FROM {{ snowflake_database }}.SILVER.SILVER_INVENTORY),
                    CURRENT_DATE()
                )
            ) AS MIN_DATE,
            GREATEST(
                COALESCE(
                    (SELECT MAX(TRANSACTION_DATE) FROM {{ snowflake_database }}.SILVER.SILVER_SALES),
                    CURRENT_DATE()
                ),
                COALESCE(
                    (SELECT MAX(SNAPSHOT_DATE) FROM {{ snowflake_database }}.SILVER.SILVER_INVENTORY),
                    CURRENT_DATE()
                )
            ) AS MAX_DATE
    ),
    DATES AS (
        SELECT DATEADD(day, SEQ4(), BOUNDS.MIN_DATE) AS FULL_DATE
        FROM TABLE(GENERATOR(ROWCOUNT => 20000)) AS DATE_GENERATOR
        CROSS JOIN BOUNDS
    )
    SELECT
        TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')) AS DATE_SK,
        FULL_DATE,
        DAYNAME(FULL_DATE) AS DAY_NAME,
        DAYOFWEEK(FULL_DATE) AS DAY_OF_WEEK,
        DAYOFMONTH(FULL_DATE) AS DAY_OF_MONTH,
        DAYOFYEAR(FULL_DATE) AS DAY_OF_YEAR,
        MONTH(FULL_DATE) AS MONTH_NUM,
        MONTHNAME(FULL_DATE) AS MONTH_NAME,
        QUARTER(FULL_DATE) AS QUARTER_NUM,
        YEAR(FULL_DATE) AS YEAR_NUM,
        YEAR(FULL_DATE) AS FISCAL_YEAR_NUM,
        QUARTER(FULL_DATE) AS FISCAL_QUARTER_NUM,
        WEEKOFYEAR(FULL_DATE) AS WEEK_OF_YEAR,
        IFF(DAYOFWEEK(FULL_DATE) IN (0, 6), TRUE, FALSE) AS IS_WEEKEND
    FROM DATES
    WHERE FULL_DATE <= (SELECT MAX_DATE FROM BOUNDS)
) AS SOURCE
ON TARGET.DATE_SK = SOURCE.DATE_SK

WHEN MATCHED THEN UPDATE SET
    TARGET.FULL_DATE = SOURCE.FULL_DATE,
    TARGET.DAY_NAME = SOURCE.DAY_NAME,
    TARGET.DAY_OF_WEEK = SOURCE.DAY_OF_WEEK,
    TARGET.DAY_OF_MONTH = SOURCE.DAY_OF_MONTH,
    TARGET.DAY_OF_YEAR = SOURCE.DAY_OF_YEAR,
    TARGET.MONTH_NUM = SOURCE.MONTH_NUM,
    TARGET.MONTH_NAME = SOURCE.MONTH_NAME,
    TARGET.QUARTER_NUM = SOURCE.QUARTER_NUM,
    TARGET.YEAR_NUM = SOURCE.YEAR_NUM,
    TARGET.FISCAL_YEAR_NUM = SOURCE.FISCAL_YEAR_NUM,
    TARGET.FISCAL_QUARTER_NUM = SOURCE.FISCAL_QUARTER_NUM,
    TARGET.WEEK_OF_YEAR = SOURCE.WEEK_OF_YEAR,
    TARGET.IS_WEEKEND = SOURCE.IS_WEEKEND

WHEN NOT MATCHED THEN INSERT (
    DATE_SK,
    FULL_DATE,
    DAY_NAME,
    DAY_OF_WEEK,
    DAY_OF_MONTH,
    DAY_OF_YEAR,
    MONTH_NUM,
    MONTH_NAME,
    QUARTER_NUM,
    YEAR_NUM,
    FISCAL_YEAR_NUM,
    FISCAL_QUARTER_NUM,
    WEEK_OF_YEAR,
    IS_WEEKEND
)
VALUES (
    SOURCE.DATE_SK,
    SOURCE.FULL_DATE,
    SOURCE.DAY_NAME,
    SOURCE.DAY_OF_WEEK,
    SOURCE.DAY_OF_MONTH,
    SOURCE.DAY_OF_YEAR,
    SOURCE.MONTH_NUM,
    SOURCE.MONTH_NAME,
    SOURCE.QUARTER_NUM,
    SOURCE.YEAR_NUM,
    SOURCE.FISCAL_YEAR_NUM,
    SOURCE.FISCAL_QUARTER_NUM,
    SOURCE.WEEK_OF_YEAR,
    SOURCE.IS_WEEKEND
);
