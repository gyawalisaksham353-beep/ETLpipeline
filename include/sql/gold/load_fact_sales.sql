-- Grain: one transaction line, keyed by TRANSACTION_ID + TRANSACTION_LINE_ID.
MERGE INTO {{ snowflake_database }}.FACTS.FCT_SALES AS TARGET
USING (
    SELECT
        MD5(CONCAT_WS(
            '|',
            SILVER_SALES.TRANSACTION_ID,
            SILVER_SALES.TRANSACTION_LINE_ID
        )) AS FCT_SALES_SK,
        SILVER_SALES.TRANSACTION_ID,
        SILVER_SALES.TRANSACTION_LINE_ID,
        SILVER_SALES.STORE_ID,
        SILVER_SALES.ITEM_ID,
        DIM_DAY.DATE_SK,
        DIM_ITEM.ITEM_SK,
        DIM_LOCN.LOCN_SK,
        SILVER_SALES.QUANTITY,
        SILVER_SALES.UNIT_PRICE,
        SILVER_SALES.DISCOUNT_AMT,
        SILVER_SALES.GROSS_SALES_AMT,
        SILVER_SALES.NET_SALES_AMT,
        SILVER_SALES.SRC_FILE_NM,
        SILVER_SALES.BATCH_ID
    FROM {{ snowflake_database }}.SILVER.SILVER_SALES AS SILVER_SALES
    INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_ITEM AS DIM_ITEM
        ON DIM_ITEM.ITEM_ID = SILVER_SALES.ITEM_ID
        AND SILVER_SALES.TRANSACTION_DATE BETWEEN
            DIM_ITEM.EFFECTIVE_FROM
            AND COALESCE(DIM_ITEM.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_LOCN AS DIM_LOCN
        ON DIM_LOCN.STORE_ID = SILVER_SALES.STORE_ID
        AND SILVER_SALES.TRANSACTION_DATE BETWEEN
            DIM_LOCN.EFFECTIVE_FROM
            AND COALESCE(DIM_LOCN.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DAY AS DIM_DAY
        ON DIM_DAY.FULL_DATE = SILVER_SALES.TRANSACTION_DATE
) AS SOURCE
ON TARGET.TRANSACTION_ID = SOURCE.TRANSACTION_ID
    AND TARGET.TRANSACTION_LINE_ID = SOURCE.TRANSACTION_LINE_ID

WHEN MATCHED AND (
    TARGET.STORE_ID IS DISTINCT FROM SOURCE.STORE_ID
    OR TARGET.ITEM_ID IS DISTINCT FROM SOURCE.ITEM_ID
    OR TARGET.DATE_SK IS DISTINCT FROM SOURCE.DATE_SK
    OR TARGET.ITEM_SK IS DISTINCT FROM SOURCE.ITEM_SK
    OR TARGET.LOCN_SK IS DISTINCT FROM SOURCE.LOCN_SK
    OR TARGET.QUANTITY IS DISTINCT FROM SOURCE.QUANTITY
    OR TARGET.UNIT_PRICE IS DISTINCT FROM SOURCE.UNIT_PRICE
    OR TARGET.DISCOUNT_AMT IS DISTINCT FROM SOURCE.DISCOUNT_AMT
    OR TARGET.GROSS_SALES_AMT IS DISTINCT FROM SOURCE.GROSS_SALES_AMT
    OR TARGET.NET_SALES_AMT IS DISTINCT FROM SOURCE.NET_SALES_AMT
    OR TARGET.SRC_FILE_NM IS DISTINCT FROM SOURCE.SRC_FILE_NM
    OR TARGET.BATCH_ID IS DISTINCT FROM SOURCE.BATCH_ID
) THEN UPDATE SET
    TARGET.STORE_ID = SOURCE.STORE_ID,
    TARGET.ITEM_ID = SOURCE.ITEM_ID,
    TARGET.DATE_SK = SOURCE.DATE_SK,
    TARGET.ITEM_SK = SOURCE.ITEM_SK,
    TARGET.LOCN_SK = SOURCE.LOCN_SK,
    TARGET.QUANTITY = SOURCE.QUANTITY,
    TARGET.UNIT_PRICE = SOURCE.UNIT_PRICE,
    TARGET.DISCOUNT_AMT = SOURCE.DISCOUNT_AMT,
    TARGET.GROSS_SALES_AMT = SOURCE.GROSS_SALES_AMT,
    TARGET.NET_SALES_AMT = SOURCE.NET_SALES_AMT,
    TARGET.SRC_FILE_NM = SOURCE.SRC_FILE_NM,
    TARGET.BATCH_ID = SOURCE.BATCH_ID,
    TARGET.LOAD_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    FCT_SALES_SK,
    TRANSACTION_ID,
    TRANSACTION_LINE_ID,
    STORE_ID,
    ITEM_ID,
    DATE_SK,
    ITEM_SK,
    LOCN_SK,
    QUANTITY,
    UNIT_PRICE,
    DISCOUNT_AMT,
    GROSS_SALES_AMT,
    NET_SALES_AMT,
    SRC_FILE_NM,
    BATCH_ID
)
VALUES (
    SOURCE.FCT_SALES_SK,
    SOURCE.TRANSACTION_ID,
    SOURCE.TRANSACTION_LINE_ID,
    SOURCE.STORE_ID,
    SOURCE.ITEM_ID,
    SOURCE.DATE_SK,
    SOURCE.ITEM_SK,
    SOURCE.LOCN_SK,
    SOURCE.QUANTITY,
    SOURCE.UNIT_PRICE,
    SOURCE.DISCOUNT_AMT,
    SOURCE.GROSS_SALES_AMT,
    SOURCE.NET_SALES_AMT,
    SOURCE.SRC_FILE_NM,
    SOURCE.BATCH_ID
);
