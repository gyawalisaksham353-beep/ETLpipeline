CREATE SCHEMA IF NOT EXISTS {{ snowflake_database }}.{{ target_schema }};

CREATE OR REPLACE VIEW {{ snowflake_database }}.{{ target_schema }}.VW_SALES_BY_ITEM AS
SELECT
    DIM_DAY.FULL_DATE,
    DIM_ITEM.ITEM_ID,
    DIM_ITEM.ITEM_NAME,
    DIM_ITEM.BRAND,
    DIM_CATEGORY.CATEGORY_NAME AS CATEGORY,
    DIM_SUBCLASS.SUBCLASS_ID,
    DIM_SUBCLASS.SUBCLASS_NAME,
    SUM(FCT_SALES.QUANTITY) AS UNITS_SOLD,
    SUM(FCT_SALES.GROSS_SALES_AMT) AS GROSS_SALES_AMT,
    SUM(FCT_SALES.DISCOUNT_AMT) AS DISCOUNT_AMT,
    SUM(FCT_SALES.NET_SALES_AMT) AS NET_SALES_AMT
FROM {{ snowflake_database }}.FACTS.FCT_SALES
INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_ITEM
    ON DIM_ITEM.ITEM_SK = FCT_SALES.ITEM_SK
LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_SUBCLASS
    ON DIM_SUBCLASS.SUBCLASS_SK = DIM_ITEM.SUBCLASS_SK
LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_CATEGORY
    ON DIM_CATEGORY.CATEGORY_SK = DIM_SUBCLASS.CATEGORY_SK
INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DAY
    ON DIM_DAY.DATE_SK = FCT_SALES.DATE_SK
GROUP BY
    DIM_DAY.FULL_DATE,
    DIM_ITEM.ITEM_ID,
    DIM_ITEM.ITEM_NAME,
    DIM_ITEM.BRAND,
    DIM_CATEGORY.CATEGORY_NAME,
    DIM_SUBCLASS.SUBCLASS_ID,
    DIM_SUBCLASS.SUBCLASS_NAME;

CREATE OR REPLACE VIEW {{ snowflake_database }}.{{ target_schema }}.VW_TOP_ITEMS_BY_REVENUE AS
SELECT
    DIM_ITEM.ITEM_ID,
    DIM_ITEM.ITEM_NAME,
    SUM(FCT_SALES.QUANTITY) AS UNITS_SOLD,
    SUM(FCT_SALES.NET_SALES_AMT) AS NET_REVENUE,
    RANK() OVER (ORDER BY SUM(FCT_SALES.NET_SALES_AMT) DESC) AS REVENUE_RANK
FROM {{ snowflake_database }}.FACTS.FCT_SALES
INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_ITEM
    ON DIM_ITEM.ITEM_SK = FCT_SALES.ITEM_SK
GROUP BY
    DIM_ITEM.ITEM_ID,
    DIM_ITEM.ITEM_NAME;

