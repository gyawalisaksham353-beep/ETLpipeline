CREATE OR REPLACE VIEW {{ snowflake_database }}.{{ target_schema }}.VW_INVENTORY_BY_STORE_ITEM AS
SELECT
    DIM_ITEM.ITEM_ID,
    DIM_ITEM.ITEM_NAME,
    DIM_LOCN.STORE_ID,
    DIM_LOCN.STORE_NAME,
    DIM_REGION.REGION_NAME AS REGION,
    FCT_INVENTORY.SNAPSHOT_DATE,
    FCT_INVENTORY.ON_HAND_QTY,
    FCT_INVENTORY.UNIT_COST,
    FCT_INVENTORY.INVENTORY_VALUE
FROM {{ snowflake_database }}.FACTS.FCT_INVENTORY
INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_ITEM
    ON DIM_ITEM.ITEM_SK = FCT_INVENTORY.ITEM_SK
INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_LOCN
    ON DIM_LOCN.LOCN_SK = FCT_INVENTORY.LOCN_SK
LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DISTRICT
    ON DIM_DISTRICT.DISTRICT_SK = DIM_LOCN.DISTRICT_SK
LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_REGION
    ON DIM_REGION.REGION_SK = DIM_DISTRICT.REGION_SK
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY FCT_INVENTORY.ITEM_ID, FCT_INVENTORY.STORE_ID
    ORDER BY FCT_INVENTORY.SNAPSHOT_DATE DESC
) = 1;

