CREATE OR REPLACE VIEW {{ snowflake_database }}.{{ target_schema }}.VW_QUARANTINE_SUMMARY AS
SELECT
    'FILE' AS QUARANTINE_TYPE,
    SOURCE_NAME,
    CAST(NULL AS VARCHAR(50)) AS SOURCE_LAYER,
    REJECTION_REASON,
    COUNT(*) AS QUARANTINE_COUNT,
    MAX(QUARANTINE_TS) AS LAST_QUARANTINE_TS
FROM {{ snowflake_database }}.QUARANTINE.FILE_QUARANTINE
GROUP BY SOURCE_NAME, REJECTION_REASON

UNION ALL

SELECT
    'RECORD' AS QUARANTINE_TYPE,
    SOURCE_NAME,
    SOURCE_LAYER,
    REJECTION_REASON,
    COUNT(*) AS QUARANTINE_COUNT,
    MAX(QUARANTINE_TS) AS LAST_QUARANTINE_TS
FROM {{ snowflake_database }}.QUARANTINE.RECORD_QUARANTINE
GROUP BY SOURCE_NAME, SOURCE_LAYER, REJECTION_REASON;
