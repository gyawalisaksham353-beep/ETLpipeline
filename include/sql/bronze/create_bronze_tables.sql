-- =====================================================
-- BRONZE LAYER
-- Raw source values are preserved as strings so that
-- malformed records can be evaluated and quarantined
-- downstream without losing data.
-- =====================================================

CREATE SCHEMA IF NOT EXISTS {{ snowflake_database }}.BRONZE;

-- Airflow validates each CSV row's field count; the COPY target also has a
-- metadata column that is not present in the source file.
CREATE FILE FORMAT IF NOT EXISTS {{ snowflake_database }}.BRONZE.BRONZE_CSV_FORMAT
    TYPE = CSV
    PARSE_HEADER = TRUE
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = FALSE
    SKIP_BYTE_ORDER_MARK = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

ALTER FILE FORMAT {{ snowflake_database }}.BRONZE.BRONZE_CSV_FORMAT
    SET ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE STAGE IF NOT EXISTS {{ snowflake_database }}.BRONZE.BRONZE_INGEST_STAGE;

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.BRONZE.BRONZE_SALES (
    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID VARCHAR(500),
    INGEST_DT DATE DEFAULT CURRENT_DATE(),

    TRANSACTION_ID VARCHAR(100),
    TRANSACTION_LINE_ID VARCHAR(100),
    STORE_ID VARCHAR(50),
    ITEM_ID VARCHAR(50),
    TRANSACTION_DATE VARCHAR(50),
    QUANTITY VARCHAR(50),
    UNIT_PRICE VARCHAR(50),
    DISCOUNT_AMT VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.BRONZE.BRONZE_ITEM_MASTER (
    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID VARCHAR(500),
    INGEST_DT DATE DEFAULT CURRENT_DATE(),

    ITEM_ID VARCHAR(100),
    ITEM_NAME VARCHAR(500),
    BRAND VARCHAR(200),
    CATEGORY VARCHAR(200),
    SUBCLASS_ID VARCHAR(100),
    SUBCLASS_NAME VARCHAR(200),
    UNIT_COST VARCHAR(100),
    LIST_PRICE VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.BRONZE.BRONZE_INVENTORY (
    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID VARCHAR(500),
    INGEST_DT DATE DEFAULT CURRENT_DATE(),

    SNAPSHOT_DATE VARCHAR(100),
    ITEM_ID VARCHAR(100),
    STORE_ID VARCHAR(100),
    ON_HAND_QTY VARCHAR(100),
    UNIT_COST VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.BRONZE.BRONZE_STORE_MASTER (
    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    INGEST_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    BATCH_ID VARCHAR(500),
    INGEST_DT DATE DEFAULT CURRENT_DATE(),

    STORE_ID VARCHAR(100),
    STORE_NAME VARCHAR(500),
    CITY VARCHAR(200),
    DISTRICT_ID VARCHAR(100),
    DISTRICT_NAME VARCHAR(200),
    REGION VARCHAR(200),
    STORE_TYPE VARCHAR(100),
    OPEN_DATE VARCHAR(100)
);
