-- =====================================================
-- CONTROL AND QUARANTINE INFRASTRUCTURE
-- Batch tracking, file/record quarantine, reconciliation
-- =====================================================

CREATE SCHEMA IF NOT EXISTS {{ snowflake_database }}.CONTROL;
CREATE SCHEMA IF NOT EXISTS {{ snowflake_database }}.QUARANTINE;

-- Tracks every discovered source file and its ingestion status.
CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.CONTROL.INGEST_BATCH (
    BATCH_ID VARCHAR(500) NOT NULL,
    SOURCE_NAME VARCHAR(100),
    SRC_FILE_NM VARCHAR(500),
    FILE_PATH VARCHAR(1000),
    FILE_HASH VARCHAR(64),
    SRC_ROW_COUNT NUMBER,
    STATUS VARCHAR(50),
    REJECTION_REASON VARCHAR(4000),
    INGEST_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Whole-file rejections (bad headers, corrupt files, unsupported sources).
CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.QUARANTINE.FILE_QUARANTINE (
    FILE_QUARANTINE_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    BATCH_ID VARCHAR(500),
    SOURCE_NAME VARCHAR(100),
    SRC_FILE_NM VARCHAR(500),
    REJECTION_REASON VARCHAR(4000),
    EXPECTED_HEADERS VARCHAR(8000),
    ACTUAL_HEADERS VARCHAR(8000),
    INGEST_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    QUARANTINE_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Row-level rejections. RAW_RECORD keeps the original source values.
CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.QUARANTINE.RECORD_QUARANTINE (
    QUARANTINE_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    BATCH_ID VARCHAR(500),
    SOURCE_NAME VARCHAR(100),
    SOURCE_LAYER VARCHAR(50),
    SRC_FILE_NM VARCHAR(500),
    SRC_ROW_NUM NUMBER,
    RAW_RECORD VARIANT,
    REASON_CODE VARCHAR(100),
    REJECTION_REASON VARCHAR(4000),
    LOAD_DATE DATE,
    INGEST_TS TIMESTAMP_NTZ,
    QUARANTINE_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Results of reconciliation checks between pipeline layers.
CREATE TABLE IF NOT EXISTS {{ snowflake_database }}.CONTROL.RECONCILIATION (
    RECON_ID VARCHAR(100),
    BATCH_ID VARCHAR(500),
    SOURCE_NAME VARCHAR(100),
    SOURCE_LAYER VARCHAR(50),
    TARGET_LAYER VARCHAR(50),
    SOURCE_RECORD_COUNT NUMBER,
    TARGET_RECORD_COUNT NUMBER,
    REJECTED_RECORD_COUNT NUMBER,
    DUPLICATE_RECORD_COUNT NUMBER,
    SOURCE_MEASURE_TOTAL NUMBER(38, 6),
    TARGET_MEASURE_TOTAL NUMBER(38, 6),
    RECON_STATUS VARCHAR(20),
    RECON_MESSAGE VARCHAR(4000),
    RECON_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Upgrade path for control tables created by earlier versions.
ALTER TABLE {{ snowflake_database }}.CONTROL.INGEST_BATCH
    ADD COLUMN IF NOT EXISTS FILE_HASH VARCHAR(64);

ALTER TABLE {{ snowflake_database }}.QUARANTINE.FILE_QUARANTINE
    ADD COLUMN IF NOT EXISTS INGEST_TS TIMESTAMP_NTZ;

ALTER TABLE {{ snowflake_database }}.QUARANTINE.RECORD_QUARANTINE
    ADD COLUMN IF NOT EXISTS INGEST_TS TIMESTAMP_NTZ;

ALTER TABLE {{ snowflake_database }}.QUARANTINE.RECORD_QUARANTINE
    ADD COLUMN IF NOT EXISTS REASON_CODE VARCHAR(100);

ALTER TABLE {{ snowflake_database }}.QUARANTINE.RECORD_QUARANTINE
    ADD COLUMN IF NOT EXISTS LOAD_DATE DATE;
