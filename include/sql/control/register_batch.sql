-- Register or refresh a discovered file in the batch control table.
MERGE INTO {{ snowflake_database }}.CONTROL.INGEST_BATCH AS TARGET
USING (
    SELECT
        %s AS BATCH_ID,
        %s AS SOURCE_NAME,
        %s AS SRC_FILE_NM,
        %s AS FILE_PATH,
        %s AS FILE_HASH,
        %s AS SRC_ROW_COUNT
) AS SOURCE
ON TARGET.BATCH_ID = SOURCE.BATCH_ID

WHEN MATCHED THEN UPDATE SET
    TARGET.SOURCE_NAME = SOURCE.SOURCE_NAME,
    TARGET.SRC_FILE_NM = SOURCE.SRC_FILE_NM,
    TARGET.FILE_PATH = SOURCE.FILE_PATH,
    TARGET.FILE_HASH = SOURCE.FILE_HASH,
    TARGET.SRC_ROW_COUNT = SOURCE.SRC_ROW_COUNT,
    TARGET.STATUS = 'DISCOVERED',
    TARGET.REJECTION_REASON = NULL,
    TARGET.UPDATED_TS = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    BATCH_ID,
    SOURCE_NAME,
    SRC_FILE_NM,
    FILE_PATH,
    FILE_HASH,
    SRC_ROW_COUNT,
    STATUS,
    INGEST_TS,
    UPDATED_TS
)
VALUES (
    SOURCE.BATCH_ID,
    SOURCE.SOURCE_NAME,
    SOURCE.SRC_FILE_NM,
    SOURCE.FILE_PATH,
    SOURCE.FILE_HASH,
    SOURCE.SRC_ROW_COUNT,
    'DISCOVERED',
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP()
);
