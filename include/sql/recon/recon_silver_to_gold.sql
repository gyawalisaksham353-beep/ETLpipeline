-- Per-batch Silver-to-Gold reconciliation for sales and inventory,
-- plus dimension history and hierarchy checks.
DELETE FROM {{ snowflake_database }}.CONTROL.RECONCILIATION
WHERE SOURCE_LAYER = 'SILVER'
  AND TARGET_LAYER = 'GOLD';

INSERT INTO {{ snowflake_database }}.CONTROL.RECONCILIATION (
    RECON_ID,
    BATCH_ID,
    SOURCE_NAME,
    SOURCE_LAYER,
    TARGET_LAYER,
    SOURCE_RECORD_COUNT,
    TARGET_RECORD_COUNT,
    REJECTED_RECORD_COUNT,
    DUPLICATE_RECORD_COUNT,
    SOURCE_MEASURE_TOTAL,
    TARGET_MEASURE_TOTAL,
    RECON_STATUS,
    RECON_MESSAGE,
    RECON_TS
)
WITH SALES_SILVER AS (
    SELECT
        BATCH_ID,
        SRC_FILE_NM,
        TRANSACTION_DATE AS BUSINESS_DATE,
        COUNT(*) AS ROW_COUNT,
        SUM(QUANTITY) AS QTY,
        SUM(GROSS_SALES_AMT) AS GROSS_AMT,
        SUM(DISCOUNT_AMT) AS DISCOUNT_AMT,
        SUM(NET_SALES_AMT) AS NET_AMT
    FROM {{ snowflake_database }}.SILVER.SILVER_SALES
    GROUP BY BATCH_ID, SRC_FILE_NM, TRANSACTION_DATE
),
SALES_GOLD AS (
    SELECT
        BATCH_ID,
        SRC_FILE_NM,
        DIM_DAY.FULL_DATE AS BUSINESS_DATE,
        COUNT(*) AS ROW_COUNT,
        SUM(QUANTITY) AS QTY,
        SUM(GROSS_SALES_AMT) AS GROSS_AMT,
        SUM(DISCOUNT_AMT) AS DISCOUNT_AMT,
        SUM(NET_SALES_AMT) AS NET_AMT
    FROM {{ snowflake_database }}.FACTS.FCT_SALES
    INNER JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DAY
        ON DIM_DAY.DATE_SK = FCT_SALES.DATE_SK
    GROUP BY BATCH_ID, SRC_FILE_NM, DIM_DAY.FULL_DATE
),
SALES_UNMATCHED AS (
    SELECT
        SILVER_SALES.BATCH_ID,
        COUNT(*) AS ROW_COUNT
    FROM {{ snowflake_database }}.SILVER.SILVER_SALES AS SILVER_SALES
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_ITEM AS DIM_ITEM
        ON DIM_ITEM.ITEM_ID = SILVER_SALES.ITEM_ID
        AND SILVER_SALES.TRANSACTION_DATE BETWEEN
            DIM_ITEM.EFFECTIVE_FROM
            AND COALESCE(DIM_ITEM.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_LOCN AS DIM_LOCN
        ON DIM_LOCN.STORE_ID = SILVER_SALES.STORE_ID
        AND SILVER_SALES.TRANSACTION_DATE BETWEEN
            DIM_LOCN.EFFECTIVE_FROM
            AND COALESCE(DIM_LOCN.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DAY
        ON DIM_DAY.FULL_DATE = SILVER_SALES.TRANSACTION_DATE
    WHERE DIM_ITEM.ITEM_SK IS NULL
       OR DIM_LOCN.LOCN_SK IS NULL
       OR DIM_DAY.DATE_SK IS NULL
    GROUP BY SILVER_SALES.BATCH_ID
),
INVENTORY_SILVER AS (
    SELECT
        BATCH_ID,
        SRC_FILE_NM,
        SNAPSHOT_DATE AS BUSINESS_DATE,
        COUNT(*) AS ROW_COUNT,
        SUM(ON_HAND_QTY) AS QTY,
        SUM(INVENTORY_VALUE) AS INV_VALUE
    FROM {{ snowflake_database }}.SILVER.SILVER_INVENTORY
    GROUP BY BATCH_ID, SRC_FILE_NM, SNAPSHOT_DATE
),
INVENTORY_GOLD AS (
    SELECT
        BATCH_ID,
        SRC_FILE_NM,
        SNAPSHOT_DATE AS BUSINESS_DATE,
        COUNT(*) AS ROW_COUNT,
        SUM(ON_HAND_QTY) AS QTY,
        SUM(INVENTORY_VALUE) AS INV_VALUE
    FROM {{ snowflake_database }}.FACTS.FCT_INVENTORY
    GROUP BY BATCH_ID, SRC_FILE_NM, SNAPSHOT_DATE
),
INVENTORY_UNMATCHED AS (
    SELECT
        SILVER_INVENTORY.BATCH_ID,
        COUNT(*) AS ROW_COUNT
    FROM {{ snowflake_database }}.SILVER.SILVER_INVENTORY AS SILVER_INVENTORY
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_ITEM AS DIM_ITEM
        ON DIM_ITEM.ITEM_ID = SILVER_INVENTORY.ITEM_ID
        AND SILVER_INVENTORY.SNAPSHOT_DATE BETWEEN
            DIM_ITEM.EFFECTIVE_FROM
            AND COALESCE(DIM_ITEM.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_LOCN AS DIM_LOCN
        ON DIM_LOCN.STORE_ID = SILVER_INVENTORY.STORE_ID
        AND SILVER_INVENTORY.SNAPSHOT_DATE BETWEEN
            DIM_LOCN.EFFECTIVE_FROM
            AND COALESCE(DIM_LOCN.EFFECTIVE_TO, TO_DATE('9999-12-31'))
    LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DAY
        ON DIM_DAY.FULL_DATE = SILVER_INVENTORY.SNAPSHOT_DATE
    WHERE DIM_ITEM.ITEM_SK IS NULL
       OR DIM_LOCN.LOCN_SK IS NULL
       OR DIM_DAY.DATE_SK IS NULL
    GROUP BY SILVER_INVENTORY.BATCH_ID
),
LATEST_ITEM_BRAND AS (
    SELECT ITEM_ID, BRAND
    FROM {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ITEM_ID
        ORDER BY SNAPSHOT_DATE DESC, SRC_ROW_NUM DESC
    ) = 1
),
ITEM_DIM_METRICS AS (
    SELECT
        COUNT(DISTINCT ITEM_ID) AS UNIQUE_ITEMS,
        COUNT_IF(IS_CURRENT) AS CURRENT_VERSIONS
    FROM {{ snowflake_database }}.DIMENSIONS.DIM_ITEM
),
ITEM_ISSUES AS (
    SELECT
        (
            SELECT COUNT(*)
            FROM {{ snowflake_database }}.DIMENSIONS.DIM_ITEM
            INNER JOIN LATEST_ITEM_BRAND USING (ITEM_ID)
            WHERE DIM_ITEM.BRAND IS DISTINCT FROM LATEST_ITEM_BRAND.BRAND
        ) AS BRAND_ISSUES,
        (
            SELECT COUNT(*)
            FROM {{ snowflake_database }}.DIMENSIONS.DIM_ITEM AS ITEM
            LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_SUBCLASS AS SUBCLASS
                ON SUBCLASS.SUBCLASS_SK = ITEM.SUBCLASS_SK
            LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_CATEGORY AS CATEGORY
                ON CATEGORY.CATEGORY_SK = SUBCLASS.CATEGORY_SK
            WHERE (ITEM.SUBCLASS_SK IS NOT NULL AND SUBCLASS.SUBCLASS_SK IS NULL)
               OR (SUBCLASS.CATEGORY_SK IS NOT NULL AND CATEGORY.CATEGORY_SK IS NULL)
        ) AS HIERARCHY_ISSUES,
        (
            WITH NEXT_VERSIONS AS (
                SELECT
                    EFFECTIVE_FROM,
                    EFFECTIVE_TO,
                    IS_CURRENT,
                    LEAD(EFFECTIVE_FROM) OVER (
                        PARTITION BY ITEM_ID
                        ORDER BY EFFECTIVE_FROM
                    ) AS NEXT_EFFECTIVE_FROM
                FROM {{ snowflake_database }}.DIMENSIONS.DIM_ITEM
            )
            SELECT COUNT(*)
            FROM NEXT_VERSIONS
            WHERE (
                    NEXT_EFFECTIVE_FROM IS NULL
                    AND (NOT IS_CURRENT OR EFFECTIVE_TO IS NOT NULL)
                )
                OR (
                    NEXT_EFFECTIVE_FROM IS NOT NULL
                    AND (
                        IS_CURRENT
                        OR EFFECTIVE_TO <> DATEADD(DAY, -1, NEXT_EFFECTIVE_FROM)
                    )
                )
        ) AS HISTORY_ISSUES
),
LOCN_DIM_METRICS AS (
    SELECT
        COUNT(DISTINCT STORE_ID) AS UNIQUE_LOCATIONS,
        COUNT_IF(IS_CURRENT) AS CURRENT_VERSIONS
    FROM {{ snowflake_database }}.DIMENSIONS.DIM_LOCN
),
LOCN_ISSUES AS (
    SELECT
        (
            SELECT COUNT(*)
            FROM {{ snowflake_database }}.DIMENSIONS.DIM_LOCN AS LOCN
            LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_DISTRICT AS DISTRICT
                ON DISTRICT.DISTRICT_SK = LOCN.DISTRICT_SK
            LEFT JOIN {{ snowflake_database }}.DIMENSIONS.DIM_REGION AS REGION
                ON REGION.REGION_SK = DISTRICT.REGION_SK
            WHERE (LOCN.DISTRICT_SK IS NOT NULL AND DISTRICT.DISTRICT_SK IS NULL)
               OR (DISTRICT.REGION_SK IS NOT NULL AND REGION.REGION_SK IS NULL)
        ) AS HIERARCHY_ISSUES,
        (
            WITH NEXT_VERSIONS AS (
                SELECT
                    EFFECTIVE_FROM,
                    EFFECTIVE_TO,
                    IS_CURRENT,
                    LEAD(EFFECTIVE_FROM) OVER (
                        PARTITION BY STORE_ID
                        ORDER BY EFFECTIVE_FROM
                    ) AS NEXT_EFFECTIVE_FROM
                FROM {{ snowflake_database }}.DIMENSIONS.DIM_LOCN
            )
            SELECT COUNT(*)
            FROM NEXT_VERSIONS
            WHERE (
                    NEXT_EFFECTIVE_FROM IS NULL
                    AND (NOT IS_CURRENT OR EFFECTIVE_TO IS NOT NULL)
                )
                OR (
                    NEXT_EFFECTIVE_FROM IS NOT NULL
                    AND (
                        IS_CURRENT
                        OR EFFECTIVE_TO <> DATEADD(DAY, -1, NEXT_EFFECTIVE_FROM)
                    )
                )
        ) AS HISTORY_ISSUES
),
INVENTORY_POSITION_ISSUES AS (
    WITH NEXT_POSITIONS AS (
        SELECT
            ITEM_ID,
            STORE_ID,
            SNAPSHOT_DATE,
            EFFECTIVE_TO,
            IS_CURRENT,
            LEAD(SNAPSHOT_DATE) OVER (
                PARTITION BY ITEM_ID, STORE_ID
                ORDER BY SNAPSHOT_DATE
            ) AS NEXT_SNAPSHOT_DATE
        FROM {{ snowflake_database }}.FACTS.FCT_INVENTORY
    )
    SELECT COUNT(*) AS CNT
    FROM NEXT_POSITIONS
    WHERE (
            NEXT_SNAPSHOT_DATE IS NULL
            AND (NOT IS_CURRENT OR EFFECTIVE_TO IS NOT NULL)
        )
        OR (
            NEXT_SNAPSHOT_DATE IS NOT NULL
            AND (
                IS_CURRENT
                OR EFFECTIVE_TO <> DATEADD(DAY, -1, NEXT_SNAPSHOT_DATE)
            )
        )
)
SELECT
    UUID_STRING(),
    SALES_SILVER.BATCH_ID,
    'pos_sales',
    'SILVER',
    'GOLD',
    SALES_SILVER.ROW_COUNT,
    COALESCE(SALES_GOLD.ROW_COUNT, 0),
    COALESCE(SALES_UNMATCHED.ROW_COUNT, 0),
    0,
    SALES_SILVER.NET_AMT,
    COALESCE(SALES_GOLD.NET_AMT, 0),
    IFF(
        SALES_SILVER.ROW_COUNT = COALESCE(SALES_GOLD.ROW_COUNT, 0)
        AND ABS(SALES_SILVER.QTY - COALESCE(SALES_GOLD.QTY, 0)) <= 0.01
        AND ABS(SALES_SILVER.GROSS_AMT - COALESCE(SALES_GOLD.GROSS_AMT, 0)) <= 0.01
        AND ABS(SALES_SILVER.DISCOUNT_AMT - COALESCE(SALES_GOLD.DISCOUNT_AMT, 0)) <= 0.01
        AND ABS(SALES_SILVER.NET_AMT - COALESCE(SALES_GOLD.NET_AMT, 0)) <= 0.01
        AND COALESCE(SALES_UNMATCHED.ROW_COUNT, 0) = 0,
        'PASS',
        'FAIL'
    ),
    'file=' || SALES_SILVER.SRC_FILE_NM
        || ', date=' || TO_CHAR(SALES_SILVER.BUSINESS_DATE, 'YYYY-MM-DD')
        || ', silver=' || SALES_SILVER.ROW_COUNT
        || ', gold=' || COALESCE(SALES_GOLD.ROW_COUNT, 0)
        || ', net_silver=' || SALES_SILVER.NET_AMT
        || ', net_gold=' || COALESCE(SALES_GOLD.NET_AMT, 0)
        || ', unmatched_keys=' || COALESCE(SALES_UNMATCHED.ROW_COUNT, 0),
    CURRENT_TIMESTAMP()
FROM SALES_SILVER
LEFT JOIN SALES_GOLD
    ON SALES_GOLD.BATCH_ID = SALES_SILVER.BATCH_ID
    AND SALES_GOLD.BUSINESS_DATE = SALES_SILVER.BUSINESS_DATE
LEFT JOIN SALES_UNMATCHED
    ON SALES_UNMATCHED.BATCH_ID = SALES_SILVER.BATCH_ID

UNION ALL

SELECT
    UUID_STRING(),
    INVENTORY_SILVER.BATCH_ID,
    'inventory',
    'SILVER',
    'GOLD',
    INVENTORY_SILVER.ROW_COUNT,
    COALESCE(INVENTORY_GOLD.ROW_COUNT, 0),
    COALESCE(INVENTORY_UNMATCHED.ROW_COUNT, 0),
    0,
    INVENTORY_SILVER.QTY,
    COALESCE(INVENTORY_GOLD.QTY, 0),
    IFF(
        INVENTORY_SILVER.ROW_COUNT = COALESCE(INVENTORY_GOLD.ROW_COUNT, 0)
        AND ABS(INVENTORY_SILVER.QTY - COALESCE(INVENTORY_GOLD.QTY, 0)) <= 0.01
        AND ABS(INVENTORY_SILVER.INV_VALUE - COALESCE(INVENTORY_GOLD.INV_VALUE, 0)) <= 0.01
        AND COALESCE(INVENTORY_UNMATCHED.ROW_COUNT, 0) = 0
        AND INVENTORY_POSITION_ISSUES.CNT = 0,
        'PASS',
        'FAIL'
    ),
    'file=' || INVENTORY_SILVER.SRC_FILE_NM
        || ', date=' || TO_CHAR(INVENTORY_SILVER.BUSINESS_DATE, 'YYYY-MM-DD')
        || ', silver=' || INVENTORY_SILVER.ROW_COUNT
        || ', gold=' || COALESCE(INVENTORY_GOLD.ROW_COUNT, 0)
        || ', on_hand_silver=' || INVENTORY_SILVER.QTY
        || ', on_hand_gold=' || COALESCE(INVENTORY_GOLD.QTY, 0)
        || ', invalid_position_closures=' || INVENTORY_POSITION_ISSUES.CNT,
    CURRENT_TIMESTAMP()
FROM INVENTORY_SILVER
LEFT JOIN INVENTORY_GOLD
    ON INVENTORY_GOLD.BATCH_ID = INVENTORY_SILVER.BATCH_ID
    AND INVENTORY_GOLD.BUSINESS_DATE = INVENTORY_SILVER.BUSINESS_DATE
LEFT JOIN INVENTORY_UNMATCHED
    ON INVENTORY_UNMATCHED.BATCH_ID = INVENTORY_SILVER.BATCH_ID
CROSS JOIN INVENTORY_POSITION_ISSUES

UNION ALL

SELECT
    UUID_STRING(),
    NULL,
    'item_master',
    'SILVER',
    'GOLD',
    COUNT(DISTINCT SILVER_ITEM_MASTER.ITEM_ID),
    ITEM_DIM_METRICS.UNIQUE_ITEMS,
    ITEM_ISSUES.HIERARCHY_ISSUES + ITEM_ISSUES.BRAND_ISSUES,
    ITEM_ISSUES.HISTORY_ISSUES,
    NULL,
    ITEM_DIM_METRICS.CURRENT_VERSIONS,
    IFF(
        COUNT(DISTINCT SILVER_ITEM_MASTER.ITEM_ID) = ITEM_DIM_METRICS.UNIQUE_ITEMS
        AND ITEM_DIM_METRICS.CURRENT_VERSIONS = ITEM_DIM_METRICS.UNIQUE_ITEMS
        AND ITEM_ISSUES.HIERARCHY_ISSUES = 0
        AND ITEM_ISSUES.BRAND_ISSUES = 0
        AND ITEM_ISSUES.HISTORY_ISSUES = 0,
        'PASS',
        'FAIL'
    ),
    'unique_items=' || COUNT(DISTINCT SILVER_ITEM_MASTER.ITEM_ID)
        || ', dimension_items=' || ITEM_DIM_METRICS.UNIQUE_ITEMS
        || ', current_versions=' || ITEM_DIM_METRICS.CURRENT_VERSIONS
        || ', brand_issues=' || ITEM_ISSUES.BRAND_ISSUES
        || ', hierarchy_issues=' || ITEM_ISSUES.HIERARCHY_ISSUES
        || ', history_issues=' || ITEM_ISSUES.HISTORY_ISSUES,
    CURRENT_TIMESTAMP()
FROM {{ snowflake_database }}.SILVER.SILVER_ITEM_MASTER
CROSS JOIN ITEM_DIM_METRICS
CROSS JOIN ITEM_ISSUES
GROUP BY
    ITEM_DIM_METRICS.UNIQUE_ITEMS,
    ITEM_DIM_METRICS.CURRENT_VERSIONS,
    ITEM_ISSUES.HIERARCHY_ISSUES,
    ITEM_ISSUES.BRAND_ISSUES,
    ITEM_ISSUES.HISTORY_ISSUES

UNION ALL

SELECT
    UUID_STRING(),
    NULL,
    'store_master',
    'SILVER',
    'GOLD',
    COUNT(DISTINCT SILVER_STORE_MASTER.STORE_ID),
    LOCN_DIM_METRICS.UNIQUE_LOCATIONS,
    LOCN_ISSUES.HIERARCHY_ISSUES,
    LOCN_ISSUES.HISTORY_ISSUES,
    NULL,
    LOCN_DIM_METRICS.CURRENT_VERSIONS,
    IFF(
        COUNT(DISTINCT SILVER_STORE_MASTER.STORE_ID) = LOCN_DIM_METRICS.UNIQUE_LOCATIONS
        AND LOCN_DIM_METRICS.CURRENT_VERSIONS = LOCN_DIM_METRICS.UNIQUE_LOCATIONS
        AND LOCN_ISSUES.HIERARCHY_ISSUES = 0
        AND LOCN_ISSUES.HISTORY_ISSUES = 0,
        'PASS',
        'FAIL'
    ),
    'unique_stores=' || COUNT(DISTINCT SILVER_STORE_MASTER.STORE_ID)
        || ', location_versions=' || LOCN_DIM_METRICS.UNIQUE_LOCATIONS
        || ', current_versions=' || LOCN_DIM_METRICS.CURRENT_VERSIONS
        || ', hierarchy_issues=' || LOCN_ISSUES.HIERARCHY_ISSUES
        || ', history_issues=' || LOCN_ISSUES.HISTORY_ISSUES,
    CURRENT_TIMESTAMP()
FROM {{ snowflake_database }}.SILVER.SILVER_STORE_MASTER
CROSS JOIN LOCN_DIM_METRICS
CROSS JOIN LOCN_ISSUES
GROUP BY
    LOCN_DIM_METRICS.UNIQUE_LOCATIONS,
    LOCN_DIM_METRICS.CURRENT_VERSIONS,
    LOCN_ISSUES.HIERARCHY_ISSUES,
    LOCN_ISSUES.HISTORY_ISSUES;
