-- Latest reconciliation results for pipeline monitoring.
SELECT
    SOURCE_LAYER,
    TARGET_LAYER,
    SOURCE_NAME,
    RECON_STATUS,
    SOURCE_RECORD_COUNT,
    TARGET_RECORD_COUNT,
    REJECTED_RECORD_COUNT,
    DUPLICATE_RECORD_COUNT,
    RECON_MESSAGE
FROM {{ snowflake_database }}.CONTROL.RECONCILIATION
ORDER BY SOURCE_LAYER, TARGET_LAYER, SOURCE_NAME;
